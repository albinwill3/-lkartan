-- Run once in Supabase SQL Editor before using the updated frontend.
-- The transaction preserves report IDs and all existing vote/review links.
BEGIN;

ALTER TABLE public.venues RENAME TO reports;
ALTER TABLE public.votes RENAME COLUMN venue_id TO report_id;
ALTER TABLE public.reviews RENAME COLUMN venue_id TO report_id;

CREATE TABLE public.venues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(btrim(name)) > 0),
  lat double precision NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng double precision NOT NULL CHECK (lng BETWEEN -180 AND 180),
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Do not guess which legacy rows represent the same bar.
-- Each report starts with its own bar; verified duplicates can be linked later.
INSERT INTO public.venues (id, name, lat, lng, user_id)
SELECT id, COALESCE(NULLIF(btrim(name), ''), 'Okänt ställe'), lat, lng, user_id
FROM public.reports;

SELECT setval(
  pg_get_serial_sequence('public.venues', 'id'),
  COALESCE((SELECT max(id) FROM public.venues), 1),
  EXISTS (SELECT 1 FROM public.venues)
);

ALTER TABLE public.reports ADD COLUMN venue_id bigint REFERENCES public.venues(id);
UPDATE public.reports SET venue_id = id;
ALTER TABLE public.reports ALTER COLUMN venue_id SET NOT NULL;
CREATE INDEX reports_venue_id_idx ON public.reports(venue_id);

-- Preserve existing timestamps if present. Unknown old dates remain NULL.
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS created_at timestamptz;
ALTER TABLE public.reports ALTER COLUMN created_at SET DEFAULT now();

-- Retain legacy name/coordinate columns as snapshots, including any NOT NULL
-- constraints, while making the venue row the canonical identity and location.
CREATE FUNCTION public.fill_report_venue_snapshot()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  SELECT name, lat, lng INTO NEW.name, NEW.lat, NEW.lng
  FROM public.venues WHERE id = NEW.venue_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Venue does not exist or is not readable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER fill_report_venue_snapshot
BEFORE INSERT OR UPDATE OF venue_id ON public.reports
FOR EACH ROW EXECUTE FUNCTION public.fill_report_venue_snapshot();

ALTER TABLE public.venues ENABLE ROW LEVEL SECURITY;
CREATE POLICY venues_read ON public.venues FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY venues_insert ON public.venues FOR INSERT TO authenticated
WITH CHECK (user_id = (SELECT auth.uid()));

-- Replace inherited policies so inserts are checked against report ownership.
DO $$
DECLARE
  existing_policy record;
BEGIN
  FOR existing_policy IN
    SELECT policyname FROM pg_policies WHERE schemaname = 'public' AND tablename = 'reports'
  LOOP
    EXECUTE format('DROP POLICY %I ON public.reports', existing_policy.policyname);
  END LOOP;
END;
$$;

ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
CREATE POLICY reports_read ON public.reports FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY reports_insert ON public.reports FOR INSERT TO authenticated
WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY reports_update ON public.reports FOR UPDATE TO authenticated
USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY reports_delete ON public.reports FOR DELETE TO authenticated
USING (user_id = (SELECT auth.uid()));

GRANT SELECT ON public.venues, public.reports TO anon, authenticated;
GRANT INSERT ON public.venues, public.reports TO authenticated;
DO $$
BEGIN
  EXECUTE format('GRANT USAGE ON SEQUENCE %s TO authenticated',
    pg_get_serial_sequence('public.venues', 'id'));
END;
$$;

-- Creating a bar and its first report is one atomic operation under RLS.
CREATE FUNCTION public.create_venue_with_report(
  venue_name text,
  venue_lat double precision,
  venue_lng double precision,
  report_data jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  new_venue_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in to add a venue';
  END IF;
  IF COALESCE((report_data->>'price')::numeric, 0) <= 0
    OR COALESCE((report_data->>'volym')::numeric, 0) <= 0 THEN
    RAISE EXCEPTION 'Price and volume must be greater than zero';
  END IF;

  INSERT INTO public.venues (name, lat, lng, user_id)
  VALUES (btrim(venue_name), venue_lat, venue_lng, auth.uid())
  RETURNING id INTO new_venue_id;

  INSERT INTO public.reports (
    venue_id, price, volym, "kannaPrice", guinness, "beerType", temperature, rating, user_id
  ) VALUES (
    new_venue_id,
    (report_data->>'price')::numeric,
    (report_data->>'volym')::numeric,
    COALESCE((report_data->>'kannaPrice')::numeric, 0),
    COALESCE((report_data->>'guinness')::boolean, false),
    COALESCE(report_data->>'beerType', ''),
    (report_data->>'temperature')::integer,
    (report_data->>'rating')::integer,
    auth.uid()
  );
  RETURN new_venue_id;
END;
$$;

REVOKE ALL ON FUNCTION public.create_venue_with_report(text, double precision, double precision, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_venue_with_report(text, double precision, double precision, jsonb) TO authenticated;

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['venues', 'reports', 'reviews', 'votes']
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables AS published
      WHERE published.pubname = 'supabase_realtime'
        AND published.schemaname = 'public'
        AND published.tablename = table_name
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', table_name);
    END IF;
  END LOOP;
END;
$$;

COMMIT;
