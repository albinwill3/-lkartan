import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const userId = '00000000-0000-0000-0000-000000000001'
const otherUserId = '00000000-0000-0000-0000-000000000002'
const migration = await readFile(new URL('../../supabase/migrations/001_separate_venues_and_reports.sql', import.meta.url), 'utf8')
const editMigration = await readFile(new URL('../../supabase/migrations/002_report_edit_and_delete.sql', import.meta.url), 'utf8')

test('venue migration preserves links, supports shared reports, and enforces atomic authenticated creation', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      CREATE ROLE anon;
      CREATE ROLE authenticated;
      CREATE SCHEMA auth;
      CREATE TABLE auth.users (id uuid PRIMARY KEY);
      INSERT INTO auth.users VALUES ('${userId}'), ('${otherUserId}');
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
        SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
      $$;
      GRANT USAGE ON SCHEMA public, auth TO anon, authenticated;
      GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated;
      CREATE TABLE public.venues (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL, lat double precision NOT NULL, lng double precision NOT NULL,
        price numeric, volym numeric, "kannaPrice" numeric, guinness boolean,
        "beerType" text, temperature integer, rating integer CHECK (rating BETWEEN 1 AND 10),
        user_id uuid REFERENCES auth.users(id)
      );
      INSERT INTO public.venues (name, lat, lng, price, volym, rating, user_id) VALUES
        ('The Pub', 58.58, 16.18, 60, 40, 5, '${userId}'),
        ('The Pub', 58.6, 16.2, 70, 40, 6, '${otherUserId}');
      CREATE TABLE public.votes (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue_id bigint REFERENCES public.venues(id), user_id uuid, value integer,
        UNIQUE(user_id, venue_id)
      );
      CREATE TABLE public.reviews (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue_id bigint REFERENCES public.venues(id), user_id uuid, rating integer, text text
      );
      INSERT INTO public.votes (venue_id, user_id, value) VALUES (1, '${userId}', 1);
      INSERT INTO public.reviews (venue_id, user_id, rating, text) VALUES (2, '${userId}', 7, 'Good');
      ALTER TABLE public.venues ENABLE ROW LEVEL SECURITY;
      CREATE POLICY old_policy ON public.venues USING (true) WITH CHECK (true);
      GRANT SELECT, INSERT ON public.venues TO authenticated;
      GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated;
      CREATE PUBLICATION supabase_realtime;
      ALTER PUBLICATION supabase_realtime ADD TABLE public.venues, public.votes, public.reviews;
    `)
    await db.exec(migration)
    await db.exec(editMigration)
    await db.exec(editMigration)

    const { rows: links } = await db.query(`
      SELECT r.id, r.venue_id, v.lat, r.created_at
      FROM public.reports r JOIN public.venues v ON v.id = r.venue_id ORDER BY r.id
    `)
    assert.equal(links.length, 2)
    assert.deepEqual(links.map((row) => Number(row.venue_id)), [1, 2])
    assert.deepEqual(links.map((row) => row.lat), [58.58, 58.6])
    assert.ok(links.every((row) => row.created_at === null))
    assert.equal(Number((await db.query('SELECT report_id FROM public.votes')).rows[0].report_id), 1)
    assert.equal(Number((await db.query('SELECT report_id FROM public.reviews')).rows[0].report_id), 2)
    const { rows: references } = await db.query(`
      SELECT confrelid::regclass::text AS target FROM pg_constraint
      WHERE contype = 'f' AND conrelid IN ('public.votes'::regclass, 'public.reviews'::regclass)
    `)
    assert.ok(references.every((row) => row.target === 'reports'))
    const { rows: publications } = await db.query(`
      SELECT tablename FROM pg_publication_tables WHERE pubname = 'supabase_realtime' ORDER BY tablename
    `)
    assert.deepEqual(publications.map((row) => row.tablename), ['reports', 'reviews', 'venues', 'votes'])

    await db.exec(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub', '${userId}', false);`)
    const create = (rating = 5) => db.query(`
      SELECT public.create_venue_with_report($1, $2, $3, $4::jsonb) AS id
    `, ['The Pub', 58.7, 16.3, JSON.stringify({ price: 65, volym: 40, temperature: 2, rating })])
    const venueId = Number((await create()).rows[0].id)
    assert.ok(venueId > 2, 'new venue identity must not collide with migrated IDs')
    await db.query(`
      INSERT INTO public.reports (venue_id, price, volym, rating, user_id)
      VALUES ($1, 75, 40, 6, $2)
    `, [venueId, userId])
    const { rows: reports } = await db.query(`
      SELECT name, lat, lng, created_at FROM public.reports WHERE venue_id = $1
    `, [venueId])
    assert.equal(reports.length, 2)
    assert.ok(reports.every((row) => row.name === 'The Pub' && row.lat === 58.7 && row.lng === 16.3 && row.created_at))

    const countVenues = async () => Number((await db.query('SELECT count(*) AS count FROM public.venues')).rows[0].count)
    const beforeFailure = await countVenues()
    await assert.rejects(create(99), /check constraint/)
    assert.equal(await countVenues(), beforeFailure, 'failed report must roll back its new bar')
    await assert.rejects(db.query(`
      INSERT INTO public.reports (venue_id, price, volym, rating, user_id)
      VALUES ($1, 75, 40, 6, NULL)
    `, [venueId]), /row-level security/)
    const { rows: edited } = await db.query('UPDATE public.reports SET price = 66 WHERE id = 1 RETURNING id, venue_id, created_at')
    assert.equal(edited.length, 1)
    assert.equal(Number(edited[0].id), 1)
    assert.equal(Number(edited[0].venue_id), 1)
    assert.equal(edited[0].created_at, null)
    assert.equal((await db.query('UPDATE public.reports SET price = 999 WHERE id = 2 RETURNING id')).rows.length, 0)
    assert.equal((await db.query('DELETE FROM public.reports WHERE id = 2 RETURNING id')).rows.length, 0)
    await assert.rejects(db.query('UPDATE public.reports SET user_id = $1 WHERE id = 1', [otherUserId]), /row-level security/)
    await db.exec(`RESET ROLE; INSERT INTO public.reviews (report_id, user_id, rating, text) VALUES (1, '${otherUserId}', 8, 'Other user review'); SET ROLE authenticated;`)
    assert.equal((await db.query('DELETE FROM public.reports WHERE id = 1 RETURNING id')).rows.length, 1)
    await db.exec('RESET ROLE')
    assert.equal((await db.query('SELECT * FROM public.votes WHERE report_id = 1')).rows.length, 0)
    assert.equal((await db.query('SELECT * FROM public.reviews WHERE report_id = 1')).rows.length, 0)
    assert.equal((await db.query('SELECT * FROM public.venues WHERE id = 1')).rows.length, 1)
    assert.equal((await db.query('SELECT * FROM public.reviews WHERE report_id = 2')).rows.length, 1)
    await db.exec('SET ROLE authenticated')
    await db.exec("SELECT set_config('request.jwt.claim.sub', '', false)")
    await assert.rejects(create(), /Sign in/)
    await db.exec('SET ROLE anon')
    await assert.rejects(create(), /permission denied/)
  } finally {
    await db.close()
  }
})
